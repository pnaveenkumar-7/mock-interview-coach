from datetime import datetime, timezone
from werkzeug.security import generate_password_hash, check_password_hash
from app.extensions import db


def utc_now():
    """Helper to return current timezone-aware UTC datetime."""
    return datetime.now(timezone.utc)


class Batch(db.Model):
    """
    Batch Model (e.g., 'BCA 2023-2026').
    Represents an academic cohort or class group.
    
    ER Relationship:
    - One Batch has Many Users (1-to-N).
    - Placement Officers use Batches to filter analytics and student performance.
    """
    __tablename__ = "batches"

    id = db.Column(db.Integer, primary_key=True)
    name = db.Column(db.String(100), nullable=False)
    created_at = db.Column(db.DateTime, default=utc_now)

    # 1-to-N: One Batch -> Multiple Users
    users = db.relationship("User", back_populates="batch", lazy=True)

    def __repr__(self):
        return f"<Batch {self.name}>"


class User(db.Model):
    """
    User Model (Students and Placement Officers/Admins).
    
    ER Relationships:
    - N-to-1 with Batch (nullable for Admins or unassigned students).
    - 1-to-N with InterviewSession (a student can take multiple mock interviews).
    - 1-to-N with SkillProfile (tracks student's running score across the 5 dimensions).
    """
    __tablename__ = "users"

    id = db.Column(db.Integer, primary_key=True)
    name = db.Column(db.String(100), nullable=False)
    email = db.Column(db.String(120), unique=True, nullable=False, index=True)
    password_hash = db.Column(db.String(255), nullable=False)
    role = db.Column(db.String(20), nullable=False, default="student")  # 'student' or 'admin'
    batch_id = db.Column(db.Integer, db.ForeignKey("batches.id"), nullable=True)
    created_at = db.Column(db.DateTime, default=utc_now)

    # Relationships
    batch = db.relationship("Batch", back_populates="users")
    sessions = db.relationship("InterviewSession", back_populates="user", cascade="all, delete-orphan", lazy=True)
    skill_profiles = db.relationship("SkillProfile", back_populates="user", cascade="all, delete-orphan", lazy=True)

    def set_password(self, password):
        """Hashes the password before storing in the database."""
        self.password_hash = generate_password_hash(password)

    def check_password(self, password):
        """Verifies if the provided plaintext password matches the stored hash."""
        return check_password_hash(self.password_hash, password)

    def __repr__(self):
        return f"<User {self.email} ({self.role})>"


class Question(db.Model):
    """
    Question Model.
    Represents questions either from a curated question bank or generated by LLM.
    
    ER Relationship:
    - 1-to-N with Answer (the same question can be answered across different interview sessions).
    """
    __tablename__ = "questions"

    id = db.Column(db.Integer, primary_key=True)
    text = db.Column(db.Text, nullable=False)
    type = db.Column(db.String(30), nullable=False)  # 'HR', 'technical', 'behavioral'
    difficulty = db.Column(db.String(20), nullable=False)  # 'easy', 'medium', 'hard'
    dimension_tag = db.Column(db.String(50), nullable=False)  # e.g., 'relevance', 'technical_accuracy'
    source = db.Column(db.String(20), nullable=False, default="bank")  # 'bank' or 'llm'
    ideal_points = db.Column(db.Text, nullable=True)  # Key points a strong answer should cover (one per line)

    # Relationships
    answers = db.relationship("Answer", back_populates="question", lazy=True)

    def __repr__(self):
        return f"<Question #{self.id} [{self.type} - {self.difficulty}]>"


class InterviewSession(db.Model):
    """
    InterviewSession Model.
    Represents an active or completed mock interview attempt by a user.
    
    ER Relationships:
    - N-to-1 with User (belongs to a specific student).
    - 1-to-N with Answer (a session consists of multiple answered questions).
    """
    __tablename__ = "interview_sessions"

    id = db.Column(db.Integer, primary_key=True)
    user_id = db.Column(db.Integer, db.ForeignKey("users.id"), nullable=False)
    interview_type = db.Column(db.String(50), nullable=False)  # e.g., 'Python Developer', 'HR Round'
    mode = db.Column(db.String(20), nullable=False, default="adaptive")  # 'adaptive' or 'fixed'
    started_at = db.Column(db.DateTime, default=utc_now)
    ended_at = db.Column(db.DateTime, nullable=True)
    overall_score = db.Column(db.Float, nullable=True)

    # Ordered list of question IDs for this session stored as JSON string (e.g. "[1, 4, 12]")
    question_ids = db.Column(db.Text, nullable=True)

    # Relationships
    user = db.relationship("User", back_populates="sessions")
    answers = db.relationship("Answer", back_populates="session", order_by="Answer.id", cascade="all, delete-orphan", lazy=True)

    def get_question_ids(self):
        """Returns the list of question IDs parsed from JSON."""
        if not self.question_ids:
            return []
        import json
        try:
            return json.loads(self.question_ids)
        except Exception:
            return []

    def set_question_ids(self, ids):
        """Serializes a list of question IDs to JSON string."""
        import json
        self.question_ids = json.dumps(ids)

    def __repr__(self):
        return f"<InterviewSession #{self.id} (User: {self.user_id})>"


class Answer(db.Model):
    """
    Answer Model.
    Records a student's response to a question during a mock interview.
    
    CRITICAL PRINCIPLE:
    - Stores transcripts ONLY (text format). Raw audio files are NEVER stored.
    
    ER Relationships:
    - N-to-1 with InterviewSession.
    - N-to-1 with Question.
    - 1-to-1 with Score (each answer receives exactly one evaluation score record).
    """
    __tablename__ = "answers"

    id = db.Column(db.Integer, primary_key=True)
    session_id = db.Column(db.Integer, db.ForeignKey("interview_sessions.id"), nullable=False)
    question_id = db.Column(db.Integer, db.ForeignKey("questions.id"), nullable=False)
    
    # Text transcript of the student's answer (never audio)
    transcript = db.Column(db.Text, nullable=False)
    input_method = db.Column(db.String(20), nullable=False, default="voice")  # 'voice' or 'typed'
    started_at = db.Column(db.DateTime, default=utc_now)
    ended_at = db.Column(db.DateTime, nullable=True)
    
    # Speech delivery metrics
    words_per_minute = db.Column(db.Float, nullable=True)
    filler_count = db.Column(db.Integer, default=0)
    long_pause_count = db.Column(db.Integer, default=0)

    # Relationships
    session = db.relationship("InterviewSession", back_populates="answers")
    question = db.relationship("Question", back_populates="answers")
    score = db.relationship("Score", back_populates="answer", uselist=False, cascade="all, delete-orphan")

    # Composite unique constraint to prevent duplicate answers for the same question in a session
    __table_args__ = (
        db.UniqueConstraint("session_id", "question_id", name="uq_session_question"),
    )

    def __repr__(self):
        return f"<Answer #{self.id} (Session: {self.session_id})>"


class Score(db.Model):
    """
    Score Model.
    Stores the detailed AI evaluation for a single answer across the 5 rubric dimensions.
    
    Rubric dimensions (each 1-10):
    1. Relevance
    2. Clarity & Structure
    3. Completeness
    4. Technical Accuracy
    5. Communication
    
    ER Relationship:
    - 1-to-1 with Answer.
    """
    __tablename__ = "scores"

    id = db.Column(db.Integer, primary_key=True)
    answer_id = db.Column(db.Integer, db.ForeignKey("answers.id"), unique=True, nullable=False)

    # 5 Rubric dimensions (each rated 1 to 10)
    relevance = db.Column(db.Integer, nullable=False)
    clarity = db.Column(db.Integer, nullable=False)
    completeness = db.Column(db.Integer, nullable=False)
    technical_accuracy = db.Column(db.Integer, nullable=False)
    communication = db.Column(db.Integer, nullable=False)

    # Constructive AI feedback
    explanation = db.Column(db.Text, nullable=True)
    improvement_tip = db.Column(db.Text, nullable=True)

    # Relationship
    answer = db.relationship("Answer", back_populates="score")

    def __repr__(self):
        return f"<Score #{self.id} for Answer #{self.answer_id}>"


class SkillProfile(db.Model):
    """
    SkillProfile Model.
    Tracks a student's aggregate competency in each of the 5 rubric dimensions.
    Updated after each evaluated answer to keep a running average.
    
    ER Relationship:
    - N-to-1 with User.
    - Unique constraint on (user_id, dimension) to ensure one entry per dimension per user.
    """
    __tablename__ = "skill_profiles"

    id = db.Column(db.Integer, primary_key=True)
    user_id = db.Column(db.Integer, db.ForeignKey("users.id"), nullable=False)
    dimension = db.Column(db.String(50), nullable=False)  # 'relevance', 'clarity', etc.
    running_avg = db.Column(db.Float, nullable=False, default=0.0)
    count = db.Column(db.Integer, nullable=False, default=0)
    updated_at = db.Column(db.DateTime, default=utc_now, onupdate=utc_now)

    # Relationship
    user = db.relationship("User", back_populates="skill_profiles")

    # Composite unique constraint so a user has at most one profile row per dimension
    __table_args__ = (
        db.UniqueConstraint("user_id", "dimension", name="uq_user_dimension"),
    )

    def __repr__(self):
        return f"<SkillProfile User:{self.user_id} {self.dimension}={self.running_avg:.2f}>"

